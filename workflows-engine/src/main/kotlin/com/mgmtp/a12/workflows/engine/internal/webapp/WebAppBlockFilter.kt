package com.mgmtp.a12.workflows.engine.internal.webapp

import jakarta.servlet.Filter
import jakarta.servlet.FilterChain
import jakarta.servlet.ServletRequest
import jakarta.servlet.ServletResponse
import jakarta.servlet.http.HttpServletRequest
import jakarta.servlet.http.HttpServletResponse
import org.cibseven.bpm.spring.boot.starter.property.CamundaBpmProperties
import org.springframework.stereotype.Component

@Component
class WebAppBlockFilter(val camundaBpmProperties: CamundaBpmProperties) : Filter {

    override fun doFilter(request: ServletRequest, response: ServletResponse, chain: FilterChain) {
        val httpRequest = request as HttpServletRequest
        val httpResponse = response as HttpServletResponse

        val pathSegments = httpRequest.requestURI.split("/").filter { it.isNotEmpty() }.map { "/$it" }
        if (pathSegments.isNotEmpty() && pathSegments[0] == (camundaBpmProperties.webapp.applicationPath)) {
            httpResponse.sendError(HttpServletResponse.SC_FORBIDDEN, "Access to this URL is blocked.")
            return
        }

        chain.doFilter(request, response)
    }
}
